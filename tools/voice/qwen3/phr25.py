# Ключ -> текст; у доклада о контакте шаблон зависит от голоса (разнообразие).
import json, sys
VOICES = ['grom', 'hrip', 'sokol', 'tihiy']
DIRS = ['впереди', 'впереди справа', 'справа', 'сзади справа', 'сзади', 'сзади слева', 'слева', 'впереди слева']
DIST = ['рядом', 'метров тридцать', 'метров пятьдесят', 'метров сто', 'метров двести']
def cap(s): return s[:1].upper() + s[1:]
def contact(d, b, vi):
    D = DIRS[d]
    if b == 0:
        t = (d + vi) % 3
        return ['Противник рядом, %s!' % D, '%s! Рядом, %s!' % ('Внимание', D), 'Близко! %s!' % cap(D)][t]
    t = (d + b + vi) % 3
    return ['Контакт! %s, %s!' % (cap(D), DIST[b]),
            'Противник %s, %s!' % (D, DIST[b]),
            'Вижу противника! %s, %s!' % (cap(D), DIST[b])][t]
