def split(t):
    s, _, tts = t.partition('|')
    return s, tts or s
def plain(t): return t.replace('+', '')
def build():
    out = {v: {} for v in VOICES}; tts = {v: {} for v in VOICES}; acc = {v: {} for v in VOICES}
    meta = {'whisper': [], 'dialog': [], 'radio': RADIO, 'urgent': [], 'v': 26}
    def put(v, k, t):
        s, sy = split(t)
        out[v][k] = plain(s); acc[v][k] = sy
        if plain(sy) != plain(s): tts[v][k] = plain(sy)
    for vi, v in enumerate(VOICES):
        for d in range(8):
            for b in range(5): put(v, 'ct%d_%d' % (d, b), contact(d, b, vi))
        for k, arr in FIX.items():
            for i, t in enumerate(arr): put(v, '%s%d' % (k, i), t)
        for k, t in CALL.items(): put(v, k, t)
        for k, t in MSG.items(): put(v, 'm_' + k, t)
        for si, (w, sc) in enumerate(DIALOG):
            for li, (r, t) in enumerate(sc): put(v, 'g%d_%d' % (si, li), t)
        for i, t in enumerate(WHISPER): put(v, 'w%d' % i, t)
    for si, (w, sc) in enumerate(DIALOG):
        meta['dialog'].append({'w': w, 'roles': [r for r, t in sc]})
        if w: meta['whisper'] += ['g%d_%d' % (si, li) for li in range(len(sc))]
    meta['whisper'] += ['w%d' % i for i in range(len(WHISPER))]
    meta['urgent'] = sorted(k for k in out['grom'] if k.rstrip('0123456789') in URGENT or (k.startswith('ct') and k.endswith('_0')))
    return out, tts, acc, meta
if __name__ == '__main__':
    out, tts, acc, meta = build()
    json.dump({'phr': out, 'tts': tts, 'acc': acc, 'meta': meta}, open(sys.argv[1] if len(sys.argv) > 1 else 'phr26.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    print(sum(len(x) for x in out.values()), 'clips;', len(out['grom']), 'per voice;', len(meta['urgent']), 'urgent')
